// A move counts toward the plan's value unless it was cancelled or parked.
export const COUNTED_MOVE_STATUSES = ["SCHEDULED", "AWAITING_CONFIRM", "AWAITING_APPROVAL", "FROZEN", "DONE"];

export function planValue(plan) {
  return plan.moves
    .filter((m) => COUNTED_MOVE_STATUSES.includes(m.status))
    .reduce((n, m) => n + m.gain, 0);
}
